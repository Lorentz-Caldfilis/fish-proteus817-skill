"""Capture real SDF for an authored structural queue using owned work copies.

This launches licensed Proteus on Windows. It never simulates the catalogue
parts or modifies the queue's original inputs. Native structure is distinct
from electrical behavior. Supply a queue generated by generic_structure_acceptance.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from fish_proteus.automation import Circuit, ProteusConfig
from tools.generic_structure_acceptance import compare_native_graph


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2, default=str) + "\n", encoding="utf-8")


def run(queue: Path, output: Path) -> dict:
    from runtime_adaptation.generic import Session
    from runtime_adaptation.capture import capture_window

    queue, output = queue.resolve(strict=True), output.resolve()
    config = ProteusConfig.discover()
    config.check_destination(output)
    if output.exists():
        raise FileExistsError(output)
    items = json.loads(queue.read_text(encoding="utf-8"))["native_queue"]
    if not isinstance(items, list) or not 1 <= len(items) <= 100:
        raise ValueError("Invalid native acceptance queue")
    output.mkdir(parents=True)
    result = {"schema": "fish-proteus.native-structure.v1", "queue_sha256": digest(queue),
              "status": "incomplete", "runtime_status": "not_run", "cases": []}
    for index, item in enumerate(items):
        source = Path(item["project"]).resolve(strict=True)
        if digest(source) != item["sha256"]:
            raise ValueError("Queued source identity changed")
        folder = output / f"{index:02d}-{source.stem}"
        folder.mkdir()
        project = folder / "circuit.pdsprj"
        shutil.copyfile(source, project)
        expected = json.loads(Path(item["expected"]).read_text(encoding="utf-8"))
        row = {"index": index, "source_sha256": digest(source), "source": str(source),
               "project_before_sha256": digest(project), "status": "blocked"}
        result["cases"].append(row)
        session = None
        try:
            session = Session(project, config=config)
            row["session"] = session.identity
            actual = session.export_netlist(folder / "actual.sdf")
            row["comparison"] = compare_native_graph(actual, expected)
            if expected.get("native_terminal_records"):
                for wanted in expected["native_terminal_records"]:
                    ref, pin = wanted["pin"].rsplit(".", 1)
                    matched = any(any(p["ref"] == ref and p["pin"] == pin for p in net["pins"]) and
                                  any(t["name"] == wanted["name"] and t["kind"] == wanted["kind"] for t in net["terminals"])
                                  for net in actual["nets"])
                    if not matched:
                        raise AssertionError(f"Native terminal record differs: {wanted}")
                row["terminal_records"] = {"expected": expected["native_terminal_records"], "matched": True}
            elif expected.get("terminal_kinds"):
                observed = Counter(t["kind"] for net in actual["nets"] for t in net["terminals"])
                row["terminal_types"] = {"file_glyph_kinds": expected["terminal_kinds"],
                                         "native_compile_records": dict(observed),
                                         "individual_types_verified": False,
                                         "note": "Same-name terminals use native type priority; use isolated native_terminal_records for individual kind verification"}
            row["sdf_sha256"] = digest(folder / "actual.sdf")
            window = session.show_schematic()
            capture_window(window["hwnd"], folder / "schematic.png")
            session.save()
            row["project_after_sha256"] = digest(project)
            reopened = Circuit.open(project, config=config)
            row["file_reopen_after_native_save"] = {"passed": True,
                                                     "components": len(reopened.components()),
                                                     "revision": reopened.revision}
            row["status"] = "native_verified"
        except Exception as error:
            row["error"] = {"type": type(error).__name__, "message": str(error)}
            for name in ("owned_pid", "owned_process_closed"):
                if hasattr(error, name):
                    row[name] = getattr(error, name)
        finally:
            if session is not None:
                try:
                    row["close_exit_code"] = session.close()
                    row["owned_process_closed"] = session.process.poll() is not None
                except Exception as error:
                    row["close_error"] = str(error)
                    row["status"] = "blocked"
                    if session.process.poll() is None:
                        session.process.terminate()
                        session.process.wait(timeout=10)
                    row["owned_process_closed"] = session.process.poll() is not None
        row["original_unchanged"] = digest(source) == item["sha256"]
        write(folder / "result.json", row)
        write(output / "result.json", result)
        short_error = dict(row["error"], message=row["error"]["message"][:400]) if row.get("error") else None
        print(json.dumps({"case": index, "project": source.stem, "status": row["status"],
                          "error": short_error}, ensure_ascii=False), flush=True)
    # Native ADI normalization must remain editable by the independent file API.
    suitable = next((row for row in result["cases"] if row["status"] == "native_verified"
                     and "component-edits" in row["source"]), None)
    if suitable:
        folder = output / "adi-roundtrip"
        folder.mkdir()
        original = Path(suitable["source"])
        project = folder / "native-edit.pdsprj"
        shutil.copyfile(original, project)
        session = None
        roundtrip = {"status": "blocked"}
        result["adi_roundtrip"] = roundtrip
        try:
            session = Session(project, config=config)
            row = session.set_properties("R1", VALUE="22.123k", API_NOTE="native edit preserved")
            session.save()
            session.close()
            roundtrip["native_readback"] = row
            editor = Circuit.open(project, config=config)
            editor.update("R1", value="33.4567k")
            rewritten = editor.save(folder / "file-edited.pdsprj")
            session = Session(rewritten, config=config)
            graph = session.export_netlist(folder / "roundtrip.sdf")
            if graph["parts"]["R1"]["value"] != "33.4567k":
                raise AssertionError("File edit after native ADI did not survive native reopening")
            roundtrip.update(status="native_verified", actual=graph["parts"]["R1"],
                             sdf_sha256=digest(folder / "roundtrip.sdf"))
        except Exception as error:
            roundtrip["error"] = str(error)
        finally:
            if session is not None and session.process.poll() is None:
                try:
                    session.close()
                except Exception as error:
                    roundtrip["close_error"] = str(error)
                    roundtrip["status"] = "blocked"
                    session.process.terminate(); session.process.wait(timeout=10)
            roundtrip["original_unchanged"] = digest(original) == suitable["source_sha256"]
            write(folder / "result.json", roundtrip)
    if (all(row["status"] == "native_verified" and row["original_unchanged"] and row.get("owned_process_closed")
            for row in result["cases"]) and
            (suitable is None or result.get("adi_roundtrip", {}).get("status") == "native_verified")):
        result["status"] = "native_verified"
    write(output / "result.json", result)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--queue", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    result = run(args.queue, args.output)
    print(json.dumps({"status": result["status"], "cases": len(result["cases"]),
                      "runtime_status": result["runtime_status"]}))
    return 0 if result["status"] == "native_verified" else 1


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
